// Isolated guide preview: mocked backend, synthetic shortcuts, no user captures.
import {chromium} from 'playwright'
import assert from 'node:assert/strict'
const browser=await chromium.launch({channel:'msedge',headless:true})
try{
 const page=await browser.newPage({viewport:{width:1100,height:1000}}),errors=[],requests=[]
 page.on('pageerror',error=>errors.push(error.message))
 await page.addInitScript(()=>{localStorage.setItem('snapmind.capture.shortcuts',JSON.stringify({objects:'Alt+V',save:'Ctrl+S'}));localStorage.setItem('snapmind-theme','light');localStorage.setItem('snapmind-language','zh-CN')})
 await page.route('**/api/**',route=>{
  const path=new URL(route.request().url()).pathname;requests.push({path,method:route.request().method()})
  return route.fulfill({json:path==='/api/sessions'?[]:path==='/api/health'?{mode:'demo',storage:'sqlite'}:{}})
 })
 await page.goto('http://127.0.0.1:5174')
 await page.locator('.launcher-settings-toggle').click()
 await page.getByRole('tab',{name:'功能',exact:true}).click()
 assert.equal(await page.getByRole('tab',{name:'截图工具',exact:true}).count(),0)
 const guide=page.locator('.capture-functions'),cards=guide.locator('.function-card'),search=guide.getByRole('searchbox',{name:'搜索功能'})
 await guide.waitFor()
 const expected=['chat','voiceCall','objects','rect','ellipse','arrow','pen','mosaic','text','blur','number','eyedropper','highlight','eraser','heal','lift','ocr','translate','scroll','pin','undo','redo','clear','save','cancel','copy']
 assert.deepEqual(await cards.evaluateAll(items=>items.map(item=>item.dataset.functionId)),expected)
 assert.equal(await guide.locator('.function-icon svg').count(),26)
 assert.ok(await cards.evaluateAll(items=>items.every(item=>item.querySelector('h5')?.textContent&&item.querySelector('.function-description')?.textContent.length>10&&item.querySelector('.function-instructions p')?.textContent.length>20)))
 assert.equal(await guide.locator('[data-function-id="objects"] .function-shortcut').innerText(),'Alt\n+\nV')
 assert.equal(await guide.locator('[data-function-id="save"] .function-shortcut').innerText(),'Ctrl\n+\nS')
 assert.equal(await guide.locator('[data-function-id="chat"] .function-icon .ai-chat-bubble-icon').count(),1)
 await search.fill('Backspace')
 assert.deepEqual(await cards.evaluateAll(items=>items.map(item=>item.dataset.functionId)),['objects','eraser','clear'])
 await search.fill('no-such-feature')
 await guide.getByRole('status').filter({hasText:'没有找到相关功能'}).waitFor()
 await search.fill('')
 await guide.getByRole('button',{name:'识别与截图',exact:true}).click()
 assert.deepEqual(await cards.evaluateAll(items=>items.map(item=>item.dataset.functionId)),['ocr','translate','scroll','pin'])
 assert.ok(await cards.evaluateAll(items=>items.every(item=>item.querySelector('.function-description').getBoundingClientRect().height>0&&item.querySelector('.function-instructions').getBoundingClientRect().height>0)))
 await page.waitForTimeout(200);await page.screenshot({path:'artifacts/function-guide-recognition.png'})
 await guide.getByRole('button',{name:'全部',exact:true}).click()
 await search.fill('Alt+V')
 assert.equal(await cards.count(),1)
 await search.fill('')
 await guide.getByRole('button',{name:'配置快捷键',exact:true}).click()
 assert.equal(await page.getByRole('tab',{name:'通用',exact:true}).getAttribute('aria-selected'),'true')
 // Change through the settings recorder so the guide must read live preferences.
 const row=page.locator('.tool-shortcut-row').filter({has:page.getByText('移动标注',{exact:true})})
 await row.locator('.tool-shortcut-picker button').first().click()
 await page.keyboard.press('Alt+E')
 await page.getByRole('tab',{name:'功能',exact:true}).click()
 assert.equal(await guide.locator('[data-function-id="objects"] .function-shortcut').innerText(),'Alt\n+\nE')
 assert.equal(await page.locator('.settings-tab-content').evaluate(e=>e.scrollTop),0)
 await page.waitForTimeout(200)
 await page.screenshot({path:'artifacts/function-guide.png'})
 await page.setViewportSize({width:390,height:844})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
 assert.equal(await page.locator('.settings-tab-content').evaluate(e=>e.scrollWidth<=e.clientWidth),true)
 assert.equal(await guide.locator('.functions-grid').first().evaluate(e=>getComputedStyle(e).gridTemplateColumns.split(' ').length),1)
 await page.screenshot({path:'artifacts/function-guide-mobile.png'})
 await page.getByRole('tab',{name:'通用',exact:true}).click()
 await page.getByRole('button',{name:'深色',exact:true}).click()
 await page.getByRole('tab',{name:'功能',exact:true}).click()
 assert.equal(await page.locator('html').getAttribute('data-theme'),'dark')
 await page.screenshot({path:'artifacts/function-guide-dark.png'})
 assert.deepEqual(requests.filter(r=>r.method!=='GET'&&/^\/api\/(capture|tools\/call|settings\/models)/.test(r.path)),[],'The guide must not perform capture or provider actions')
 assert.deepEqual(errors,[])
 console.log('PASS: all 25 toolbar icons, names and detailed instructions; current shortcut updates; search, categories, settings navigation, narrow layout and dark theme. Isolated mocked APIs only.')
}finally{await browser.close()}
