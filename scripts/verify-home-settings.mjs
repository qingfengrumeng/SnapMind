import {chromium} from 'playwright'
import assert from 'node:assert/strict'
import {resolve} from 'node:path'
const native=process.argv.includes('--native')
const browser=native?await chromium.connectOverCDP('http://127.0.0.1:9223'):await chromium.launch({channel:'msedge',headless:true})
const context=native?browser.contexts()[0]:await browser.newContext({viewport:{width:1100,height:1000}})
const page=native?context.pages().find(p=>p.url().includes('5174')&&!p.url().includes('desktop=')):await context.newPage()
const invoke=(command,args)=>page.evaluate(({command,args})=>window.__TAURI_INTERNALS__.invoke(command,args),{command,args})
const windowModule='/@fs/'+resolve('node_modules/@tauri-apps/api/window.js').replaceAll('\\','/')
const errors=[];page.on('pageerror',e=>errors.push(e.message))
let original
try{
 if(native){await invoke('show_launcher');await page.reload()}else await page.goto('http://127.0.0.1:5173')
 await page.locator('.snapmind-home').waitFor()
 const homeSize=await page.locator('.snapmind-home').boundingBox()
 assert.ok(homeSize.width>homeSize.height,'Launcher should have landscape proportions')
 assert.ok(homeSize.width<=805,'Launcher should remain moderately wide')
 const originalGallery=await page.evaluate(()=>localStorage.getItem('snapmind-gallery-view'))
 await page.getByRole('button',{name:'网格展示',exact:true}).evaluate(e=>e.click())
 await page.waitForFunction(()=>[...document.querySelectorAll('.shot-thumbnail img')].slice(0,2).every(img=>img.complete&&img.naturalWidth>0))
 if(await page.locator('.launcher-recent-grid').count())assert.equal(await page.locator('.launcher-recent-grid').evaluate(e=>getComputedStyle(e).gridTemplateColumns.split(' ').length),2)
 await page.screenshot({path:native?'artifacts/native-home-landscape.png':'artifacts/home-landscape.png'})
 if(originalGallery==='list')await page.getByRole('button',{name:'列表展示',exact:true}).evaluate(e=>e.click())
 original=native?(await invoke('get_desktop_state')).captureShortcut:await page.evaluate(()=>localStorage.getItem('snapmind-capture-shortcut'))
 assert.equal(await page.locator('.launcher-brand-logo button').count(),0)
 assert.equal(await page.locator('.launcher-menu-toggle,.launcher-shortcut-hint,.launcher-capture-fab').count(),0)
 assert.equal(await page.locator('.window-control-divider').count(),1)
 assert.equal(await page.locator('.window-controls .launcher-settings-toggle').count(),1)
 const settings=page.getByRole('button',{name:'设置与工具',exact:true}),panel=page.getByRole('navigation',{name:'设置与工具面板',exact:true})
 const click=async locator=>native?locator.evaluate(e=>e.click()):locator.click()
 await click(settings);await panel.waitFor()
 assert.equal(await panel.getByRole('button',{name:'关闭工具窗口',exact:true}).count(),0)
 const surface=await page.locator('.snapmind-home').boundingBox(),settingsSurface=await panel.boundingBox()
 assert.ok(Math.abs(settingsSurface.width-surface.width)<=2)
 assert.ok(Math.abs(settingsSurface.y+settingsSurface.height-surface.y-surface.height)<=2)
 await page.screenshot({path:native?'artifacts/native-home-settings.png':'artifacts/home-settings.png'})
 await click(page.locator('.launcher-name'));await panel.waitFor()
 await page.evaluate(()=>window.dispatchEvent(new Event('blur')));await panel.waitFor()
 await click(settings);await panel.waitFor({state:'detached'})
 await click(settings);await settings.focus();await settings.press('Escape');await panel.waitFor({state:'detached'})
 await click(settings)
 if(native){
  // Settings remain open when another native window receives focus.
  await invoke('show_workspace');await panel.waitFor()
  const work=context.pages().find(p=>p.url().includes('desktop=workspace'))
  await work.evaluate(async path=>{const {getCurrentWindow}=await import(path);await getCurrentWindow().hide()},windowModule)
  await invoke('show_launcher');await panel.waitFor()
  const invalid=await invoke('set_capture_shortcut',{shortcut:'K'}).then(()=>null,e=>String(e))
  assert.ok(invalid);assert.equal((await invoke('get_desktop_state')).captureShortcut,original)
 }
 await click(page.getByRole('tab',{name:'通用',exact:true}))
 const recorder=page.getByRole('button',{name:'录制截图快捷键',exact:true})
 await click(recorder);await recorder.focus();await recorder.locator('kbd').filter({hasText:'按下组合键'}).waitFor()
 await recorder.press('Control+Alt+Shift+k')
 assert.equal(await recorder.innerText(),'Ctrl+Alt+Shift+K')
 await click(page.getByRole('button',{name:'保存截图快捷键',exact:true}))
 await page.waitForFunction(()=>localStorage.getItem('snapmind-capture-shortcut')==='Ctrl+Alt+Shift+K')
 if(native)assert.equal((await invoke('get_desktop_state')).captureShortcut,'Ctrl+Alt+Shift+K')
 await page.reload();await page.locator('.snapmind-home').waitFor();await click(settings);await click(page.getByRole('tab',{name:'通用',exact:true}))
 assert.equal(await recorder.innerText(),'Ctrl+Alt+Shift+K')
 await click(page.getByRole('button',{name:'关闭设置面板'}));await panel.waitFor({state:'detached'})
 if(!native){
  await page.getByRole('button',{name:'网格展示',exact:true}).hover()
  const tooltip=page.getByRole('tooltip');await tooltip.waitFor()
  assert.equal(await tooltip.evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(245, 239, 255)')
  const box=await tooltip.boundingBox();assert.ok(box.x>=0&&box.y>=0&&box.x+box.width<=1100)
  await page.screenshot({path:'artifacts/home-tooltip.png'})
  await page.mouse.move(0,0);await tooltip.waitFor({state:'detached'})
  await page.setViewportSize({width:390,height:844});await click(settings)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  await page.screenshot({path:'artifacts/home-settings-mobile.png'})
 }
 assert.deepEqual(errors,[])
 console.log('PASS: '+(native?'settings persist across native focus changes; ':'')+'landscape layout, settings persist on outside click/blur, explicit close/toggle/Escape, shortcut save/reload, '+(!native?'purple tooltip and mobile layout; ':'')+'no errors.')
}finally{
 if(original!==undefined){if(native)await invoke('set_capture_shortcut',{shortcut:original}).catch(()=>{});else await page.evaluate(value=>{if(value===null)localStorage.removeItem('snapmind-capture-shortcut');else localStorage.setItem('snapmind-capture-shortcut',value)},original)}
 if(native)await invoke('show_launcher').catch(()=>{})
 await browser.close()
}
