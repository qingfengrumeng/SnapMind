// Synthetic screenshot only. No finish action, clipboard writes, history or model calls.
import {chromium} from 'playwright'
import assert from 'node:assert/strict'
const b=await chromium.connectOverCDP('http://127.0.0.1:9223')
const pages=b.contexts()[0].pages(),main=pages.find(p=>p.url().includes('5174')&&!p.url().includes('desktop=')),capture=pages.find(p=>p.url().includes('desktop=capture'))
const invoke=(command,args)=>main.evaluate(({command,args})=>window.__TAURI_INTERNALS__.invoke(command,args),{command,args})
const errors=[];capture.on('pageerror',e=>errors.push(e.message))
try{
 const asset=await main.evaluate(()=>{const c=document.createElement('canvas');c.width=800;c.height=500;const g=c.getContext('2d');g.fillStyle='#fff';g.fillRect(0,0,800,500);return {id:'inline-text-test-'+Date.now(),name:'Text fixture',data:c.toDataURL('image/png'),width:800,height:500,scenario:'custom'}})
 await invoke('begin_preview_capture',{asset})
 await capture.waitForFunction(id=>{const e=document.querySelector('.capture-overlay');return e?.dataset.sourceId===id&&e.dataset.ready==='true'},asset.id)
 for(let n=0;n<50&&!(await invoke('native_status')).windows.capture.visible;n++)await main.waitForTimeout(20)
 await capture.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
 const r=await capture.locator('.capture-screen').boundingBox()
 const at=(x,y)=>({x:r.x+x*r.width/800,y:r.y+y*r.height/500})
 const start=at(80,80),end=at(700,390)
 await capture.mouse.move(start.x,start.y);await capture.mouse.down();await capture.mouse.move(end.x,end.y,{steps:5});await capture.mouse.up()
 await capture.getByRole('button',{name:'截图文字',exact:true}).click()
 assert.equal(await capture.locator('.capture-tool-options input').count(),0,'Remove the old toolbar text input')
 const location=at(150,150);await capture.mouse.click(location.x,location.y)
 const editor=capture.getByRole('textbox',{name:'截图文字标注'})
 await editor.waitFor();await capture.waitForFunction(()=>document.activeElement?.classList.contains('capture-text-editor'));assert.equal(await editor.evaluate(e=>e===document.activeElement),true)
 const box=await editor.boundingBox();assert.ok(Math.abs(box.x-location.x)<2&&Math.abs(box.y-location.y)<2,'Editor appears where the user clicks')
 await editor.fill('直接输入文字\n第二行')
 await editor.dispatchEvent('keydown',{key:'Enter',isComposing:true,bubbles:true})
 assert.equal(await editor.count(),1,'IME Enter must not commit before composition finishes')
 await capture.getByRole('button',{name:'字号 32',exact:true}).click()
 assert.equal(await editor.evaluate(e=>getComputedStyle(e).fontSize),'32px')
 await editor.press('Enter');assert.equal(await editor.count(),0)
 const changed=()=>capture.locator('.capture-screen').evaluate(c=>{const d=c.getContext('2d').getImageData(140,140,300,130).data;let n=0;for(let i=0;i<d.length;i+=4)if(d[i+1]<200)n++;return n})
 assert.ok(await changed()>20,'Committed text must be drawn into the actual screenshot pixels')
 await capture.getByRole('button',{name:'撤销截图标注',exact:true}).click()
 assert.equal(await changed(),0,'Undo restores the original screenshot')
 await capture.mouse.click(location.x,location.y);await editor.fill('Discard');await editor.press('Escape')
 assert.equal(await editor.count(),0);assert.equal((await invoke('get_desktop_state')).captureActive,true,'Esc cancels text editing rather than the screenshot')
 assert.equal(await changed(),0)
 assert.deepEqual(errors,[])
 console.log('PASS: click-to-type on screenshot, multiline input, IME, live font size, commit, undo and Escape cancellation.')
}finally{await invoke('cancel_capture').catch(()=>{});await b.close()}
