// Deterministic stripe image; no export, clipboard, history or model calls.
import {chromium} from 'playwright'
import assert from 'node:assert/strict'
const b=await chromium.connectOverCDP('http://127.0.0.1:9223')
const pages=b.contexts()[0].pages(),main=pages.find(p=>p.url().includes('5174')&&!p.url().includes('desktop=')),capture=pages.find(p=>p.url().includes('desktop=capture'))
const invoke=(command,args)=>main.evaluate(({command,args})=>window.__TAURI_INTERNALS__.invoke(command,args),{command,args})
const errors=[];capture.on('pageerror',e=>errors.push(e.message))
try{
 const asset=await main.evaluate(()=>{const c=document.createElement('canvas');c.width=800;c.height=500;const g=c.getContext('2d');g.fillStyle='#fff';g.fillRect(0,0,800,500);g.fillStyle='#000';for(let x=0;x<800;x+=2)g.fillRect(x,0,1,500);return {id:'mosaic-brush-test-'+Date.now(),name:'Mosaic fixture',data:c.toDataURL('image/png'),width:800,height:500,scenario:'custom'}})
 await invoke('begin_preview_capture',{asset})
 await capture.waitForFunction(id=>{const e=document.querySelector('.capture-overlay');return e?.dataset.sourceId===id&&e.dataset.ready==='true'},asset.id)
 for(let n=0;n<50&&!(await invoke('native_status')).windows.capture.visible;n++)await main.waitForTimeout(20)
 await capture.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
 const box=await capture.locator('.capture-screen').boundingBox(),scale=box.width/800
 const point=(x,y)=>({x:box.x+(x+.2)*scale,y:box.y+(y+.2)*scale})
 async function drag(x,y,x2,y2,steps=8){const a=point(x,y),z=point(x2,y2);await capture.mouse.move(a.x,a.y);await capture.mouse.down();await capture.mouse.move(z.x,z.y,{steps});await capture.mouse.up()}
 const pixels=(x,y,w=1,h=1)=>capture.locator('.capture-screen').evaluate((c,{x,y,w,h})=>Array.from(c.getContext('2d').getImageData(x,y,w,h).data),{x,y,w,h})
 const undo=()=>capture.getByRole('button',{name:'撤销截图标注',exact:true}).click()
 await drag(80,70,720,420)
 const selection=await capture.locator('.capture-size').innerText()
 await capture.getByRole('button',{name:'截图马赛克',exact:true}).click()
 const tools=await capture.locator('.capture-tools-scroll').boundingBox(),options=await capture.locator('.capture-tool-options').boundingBox(),crop=await capture.locator('.capture-selection').boundingBox()
 assert.ok(options.y>=tools.y+tools.height,'Function options must sit below the toolbar')
 assert.ok(tools.y>=crop.y+crop.height,'Both rows must stay below the crop when there is room')
 assert.equal(await capture.locator('.capture-tool-options .swatch').count(),0)
 assert.equal(await capture.locator('.mosaic-size-choice').count(),3)
 await capture.getByRole('button',{name:'马赛克画刷 52',exact:true}).click()
 const corner=Math.floor(52/scale/2*.85),original=await pixels(200-corner,200-corner,corner*2+1,corner*2+1),outside=await pixels(200+corner,200+corner)
 const a=point(200,200);await capture.mouse.click(a.x,a.y)
 assert.notDeepEqual(await pixels(200-corner,200-corner,corner*2+1,corner*2+1),original,'Single press must paint immediately')
 assert.deepEqual(await pixels(200+corner,200+corner),outside,'Circular brush leaves its square corners untouched')
 await undo();assert.deepEqual(await pixels(200-corner,200-corner,corner*2+1,corner*2+1),original)
 await capture.getByRole('button',{name:'正方形画刷',exact:true}).click();await capture.mouse.click(a.x,a.y)
 assert.notDeepEqual(await pixels(200+corner,200+corner),outside,'Square brush covers its corners')
 await undo()
 const pathBefore=await pixels(230,200,10,5),offPath=await pixels(230,245,10,5)
 await drag(200,200,400,200,2)
 assert.notDeepEqual(await pixels(230,200,10,5),pathBefore,'Fast brush movement must leave a continuous painted path')
 assert.deepEqual(await pixels(230,245,10,5),offPath,'Brush must not redact the bounding rectangle around its path')
 await undo();assert.deepEqual(await pixels(230,200,10,5),pathBefore)
 const cropOutside=await pixels(65,290,10,20),edge=point(80,300)
 await capture.mouse.click(edge.x,edge.y)
 assert.deepEqual(await pixels(65,290,10,20),cropOutside,'Painting near a crop edge must not affect pixels outside the screenshot')
 await undo()
 await capture.getByRole('button',{name:'一键打码',exact:true}).click()
 await capture.waitForFunction(()=>document.querySelector('.mosaic-area-button')?.classList.contains('chosen')&&!document.querySelector('.capture-overlay')?.classList.contains('mosaic-brushing'))
 const areaBefore=await pixels(350,150,100,80),outsideArea=await pixels(340,140,5,5)
 await drag(450,230,350,150)
 assert.notDeepEqual(await pixels(350,150,100,80),areaBefore,'Area mode must redact the whole dragged rectangle')
 assert.deepEqual(await pixels(340,140,5,5),outsideArea)
 assert.equal(await capture.locator('.capture-size').innerText(),selection,'Area redaction must preserve screenshot crop')
 await undo();assert.deepEqual(await pixels(350,150,100,80),areaBefore)
 assert.deepEqual(errors,[])
 console.log('PASS: options below toolbar outside crop; circular/square brush, three sizes without colors, continuous strokes, area redaction, crop clipping and one-step undo.')
}finally{await invoke('cancel_capture').catch(()=>{});await b.close()}
